'use strict';
// npm run setup        -> first-time setup: .env with random secrets, databases, demo users, records, first backup
// npm run reset-demo   -> same, but also wipes attempts/alerts/blocks, archives the log and re-seeds data
//                         (stop the server first). Use it before every rehearsal.
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const ROOT = path.join(__dirname, '..');
const ENV = path.join(ROOT, '.env');
const reset = process.argv.includes('--reset');

if (!fs.existsSync(ENV)) {
  fs.writeFileSync(ENV, [
    '# Generated by npm run setup - keep this file secret, it is excluded from Git.',
    `SESSION_SECRET=${crypto.randomBytes(32).toString('hex')}`,
    `BACKUP_KEY=${crypto.randomBytes(32).toString('hex')}`,
    'PORT=3001',
    'PROTECTION_MODE=on',
    '# Policy value is 60000 (60 s). Shortened to 10 s so the live demo does not wait minutes.',
    'BLOCK_BASE_MS=10000',
    '# Simulation only - lets the traffic scripts pose as many IPs. Never true in production.',
    'SIMULATION_TRUST_XFF=true',
    '',
  ].join('\n'));
  console.log('Created .env with fresh SESSION_SECRET and BACKUP_KEY');
}

// load config only after .env exists
const bcrypt = require('bcryptjs');
const { openSecurity, openCompany } = require('../lib/db');
const { LOG_PATH } = require('../lib/logger');
const backup = require('../lib/backup');
const { logEvent } = require('../lib/logger');

// Demo accounts. hr.manager deliberately has a legacy weak password that is in the attacker's wordlist:
// it meets the old complexity rule (11 chars, upper, lower, digit, symbol) but is a dictionary word + year.
const USERS = [
  ['secadmin',   'admin',    'Nt!S0c-Adm1n#77'],
  ['hr.manager', 'hr',       'Summer@2026'],
  ['a.hassan',   'employee', 'Ah#91-Blue-Kite'],
  ['m.farouk',   'employee', 'Mf$58-Red-Lamp'],
  ['s.nabil',    'employee', 'Sn%23-Gold-Tree'],
  ['n.adel',     'employee', 'Na&64-Grey-Boat'],
  ['k.samir',    'employee', 'Ks*37-Pink-Moon'],
];

const FIRST = ['Ahmed', 'Mona', 'Omar', 'Salma', 'Karim', 'Nour', 'Youssef', 'Laila', 'Hany', 'Dina',
  'Tarek', 'Rania', 'Mostafa', 'Heba', 'Amr', 'Yasmin', 'Sherif', 'Mai', 'Khaled', 'Aya'];
const LAST = ['Hassan', 'Farouk', 'Nabil', 'Adel', 'Samir', 'Fathy', 'Mansour', 'Saeed', 'Lotfy', 'Ezzat'];
const DEPTS = ['Finance', 'HR', 'Engineering', 'Sales', 'Operations'];

function seed() {
  const sec = openSecurity();
  const company = openCompany();
  if (reset) {
    sec.exec('DELETE FROM attempts; DELETE FROM alerts; DELETE FROM blocked_ips; DELETE FROM users;');
    sec.prepare("INSERT INTO settings (key, value) VALUES ('protection_mode', 'on') ON CONFLICT(key) DO UPDATE SET value = 'on'").run();
    if (fs.existsSync(LOG_PATH) && fs.statSync(LOG_PATH).size > 0) {
      const archived = LOG_PATH.replace(/\.log$/, `-${Date.now()}.log`);
      // Copy + empty instead of rename: on Windows a file that another program (the server or
      // detect.py --follow) has open cannot be renamed, which used to crash the reset half-way.
      try {
        fs.copyFileSync(LOG_PATH, archived);
        fs.writeFileSync(LOG_PATH, '');
        console.log('Archived old log to', path.relative(ROOT, archived));
      } catch (e) {
        console.warn('Could not archive the log (is it open somewhere?) - continuing:', e.code || e.message);
      }
    }
  }
  const insUser = sec.prepare(`INSERT INTO users (username, password_hash, role, created_at) VALUES (?, ?, ?, ?)
    ON CONFLICT(username) DO NOTHING`);
  for (const [u, role, pw] of USERS) insUser.run(u, bcrypt.hashSync(pw, 12), role, Date.now());

  const count = company.prepare('SELECT COUNT(*) AS n FROM employees').get().n;
  if (reset || count === 0) {
    company.exec('DELETE FROM employees');
    const ins = company.prepare('INSERT INTO employees (id, full_name, national_id, department, salary, phone, email) VALUES (?, ?, ?, ?, ?, ?, ?)');
    let rnd = 42;                                              // deterministic pseudo-random -> same data every time
    const r = n => (rnd = (rnd * 1103515245 + 12345) % 2147483648) % n;
    for (let i = 1; i <= 20; i++) {
      const name = `${FIRST[i - 1]} ${LAST[r(LAST.length)]}`;
      const nid = `2${String(90 + r(10)).padStart(2, '0')}${String(1 + r(12)).padStart(2, '0')}${String(1 + r(28)).padStart(2, '0')}${String(r(10000000)).padStart(7, '0')}`; // 14 digits
      ins.run(i, name, nid, DEPTS[r(DEPTS.length)], 9000 + r(41) * 1000, `+20 10${String(r(100000000)).padStart(8, '0')}`,
        `${name.split(' ')[0][0].toLowerCase()}.${name.split(' ')[1].toLowerCase()}@niletech.example`);
    }
    console.log('Seeded 20 synthetic employee records');
  }
  const m = backup.createBackup(company, reset ? 'baseline (reset)' : 'baseline (setup)');
  logEvent('BACKUP', { result: 'ok', detail: `${m.reason}: ${m.file} (${m.records} records)` });
  console.log(`Baseline backup ${m.file} (${m.records} records)`);
  console.log('\nDemo accounts (synthetic - for the live demo only):');
  for (const [u, role, pw] of USERS) console.log(`  ${u.padEnd(11)} ${role.padEnd(9)} ${pw}`);
}

seed();
